def _normalize_light_state(raw_state: Any) -> str:
    if isinstance(raw_state, bool):
        return "RED" if raw_state else "GREEN"
    if isinstance(raw_state, (int, float)):
        if int(raw_state) == 2:
            return "YELLOW"
        return "RED" if int(raw_state) == 1 else "GREEN"
    if isinstance(raw_state, str):
        s = raw_state.strip().lower()
        if s in ("red", "r", "stop"):
            return "RED"
        if s in ("green", "g", "go"):
            return "GREEN"
        if s in ("yellow", "amber", "y"):
            return "YELLOW"
    if isinstance(raw_state, dict):
        return _normalize_light_state(raw_state.get("state", raw_state.get("color", "yellow")))
    return "YELLOW"


def _light_state_color(state: str) -> str:
    if state == "RED":
        return "#E53935"
    if state == "GREEN":
        return "#43A047"
    return "#FBC02D"


def draw_traffic_lights(
    ax: plt.Axes,
    trace: TraceDict,
    map_layers: Optional[Dict[str, Any]],
    frame_idx: int,
    marker_radius_m: float = 0.45,
) -> None:
    if not map_layers:
        return
    frames = trace.get("frames", [])
    if not isinstance(frames, list) or not frames:
        return
    idx = max(0, min(frame_idx, len(frames) - 1))

    route_lane_ids_set = map_layers.get("route_lane_ids_set")
    entries = _frame_traffic_light_entries(frames[idx], route_lane_ids_set)
    if not entries:
        return

    anchors_by_lane = map_layers.get("tl_anchors_by_lane_connector", {})
    markers: List[List[Any]] = []  # [x, y, state, lane_id]
    for lane_id, state in entries:
        anchors = anchors_by_lane.get(lane_id, [])
        for anchor in anchors:
            markers.append([float(anchor[0]), float(anchor[1]), state, lane_id])

    if not markers:
        return

    # If multiple movements share one stop line center, spread markers in a tiny ring.
    grouped: Dict[Tuple[float, float], List[int]] = collections.defaultdict(list)
    for i, (x, y, _, _) in enumerate(markers):
        grouped[(round(x, 2), round(y, 2))].append(i)
    for group_indices in grouped.values():
        n = len(group_indices)
        if n <= 1:
            continue
        spread_r = 0.55
        for j, marker_idx in enumerate(group_indices):
            theta = 2.0 * math.pi * float(j) / float(n)
            markers[marker_idx][0] += spread_r * math.cos(theta)
            markers[marker_idx][1] += spread_r * math.sin(theta)

    for x, y, state, _ in markers:
        ax.add_patch(
            Circle(
                (x, y),
                radius=marker_radius_m,
                facecolor=_light_state_color(state),
                edgecolor="#111111",
                linewidth=0.55,
                alpha=0.95,
                zorder=10,
            )
        )


def _frame_traffic_light_entries(
    frame: Dict[str, Any],
    route_lane_ids_set: Optional[set[str]],
) -> List[Tuple[str, str]]:
    entries_raw = frame.get("traffic_lights", [])
    entries: List[Tuple[str, str]] = []
    if not isinstance(entries_raw, list):
        return entries
    for item in entries_raw:
        if not isinstance(item, (list, tuple)) or len(item) != 2:
            continue
        lane_id = str(item[0])
        state = _normalize_light_state(item[1])
        entries.append((lane_id, state))
    if route_lane_ids_set:
        filtered = [entry for entry in entries if entry[0] in route_lane_ids_set]
        if filtered:
            return filtered
    return entries


def _summarize_light_state(entries: List[Tuple[str, str]]) -> Tuple[str, int, int, int]:
    if not entries:
        return "N/A", 0, 0, 0
    red_count = sum(1 for _, state in entries if state == "RED")
    yellow_count = sum(1 for _, state in entries if state == "YELLOW")
    green_count = sum(1 for _, state in entries if state == "GREEN")
    if red_count > 0 and green_count == 0:
        return "RED", red_count, yellow_count, green_count
    if green_count > 0 and red_count == 0:
        return "GREEN", red_count, yellow_count, green_count
    if yellow_count > 0 and red_count == 0 and green_count == 0:
        return "YELLOW", red_count, yellow_count, green_count
    return "MIXED", red_count, yellow_count, green_count


def _estimate_countdown_seconds(
    trace: TraceDict,
    frame_idx: int,
    route_lane_ids_set: Optional[set[str]],
) -> Optional[float]:
    frames = trace.get("frames", [])
    if not isinstance(frames, list) or frame_idx >= len(frames):
        return None

    curr_entries = _frame_traffic_light_entries(frames[frame_idx], route_lane_ids_set)
    curr_state, _, _, _ = _summarize_light_state(curr_entries)
    if curr_state == "N/A":
        return None

    curr_ts = frames[frame_idx].get("timestamp")
    if curr_ts is None:
        return None

    for j in range(frame_idx + 1, len(frames)):
        next_entries = _frame_traffic_light_entries(frames[j], route_lane_ids_set)
        next_state, _, _, _ = _summarize_light_state(next_entries)
        if next_state == "N/A":
            continue
        if next_state != curr_state:
            next_ts = frames[j].get("timestamp")
            if next_ts is None:
                return None
            return max(0.0, (float(next_ts) - float(curr_ts)) / 1e6)
    return None


def infer_realtime_fps_from_trace(trace: TraceDict) -> Optional[float]:
    frames = trace.get("frames", [])
    if not isinstance(frames, list) or len(frames) < 2:
        return None
    timestamps: List[float] = []
    for frame in frames:
        ts = frame.get("timestamp")
        if ts is None:
            continue
        try:
            timestamps.append(float(ts))
        except Exception:
            continue
    if len(timestamps) < 2:
        return None
    deltas_s = []
    for i in range(len(timestamps) - 1):
        dt = (timestamps[i + 1] - timestamps[i]) / 1e6
        if dt > 1e-6:
            deltas_s.append(dt)
    if not deltas_s:
        return None
    median_dt = float(np.median(np.asarray(deltas_s, dtype=np.float64)))
    if median_dt <= 1e-6:
        return None
    return 1.0 / median_dt


def draw_traffic_light_hud(
    ax: plt.Axes,
    trace: TraceDict,
    frame_idx: int,
    map_layers: Optional[Dict[str, Any]],
) -> None:
    frames = trace.get("frames", [])
    if not isinstance(frames, list) or not frames:
        return
    idx = max(0, min(frame_idx, len(frames) - 1))
    route_lane_ids_set = None
    if map_layers is not None:
        route_lane_ids_set = map_layers.get("route_lane_ids_set")

    entries = _frame_traffic_light_entries(frames[idx], route_lane_ids_set)
    state, red_count, yellow_count, green_count = _summarize_light_state(entries)
    if state == "N/A":
        return

    countdown_s = _estimate_countdown_seconds(trace, idx, route_lane_ids_set)
    if countdown_s is None:
        countdown_text = "--"
    else:
        countdown_text = f"{countdown_s:.1f}s"

    if state == "RED":
        color = "#D32F2F"
    elif state == "GREEN":
        color = "#2E7D32"
    elif state == "YELLOW":
        color = "#F9A825"
    else:
        color = "#F9A825"

    # Right-top traffic light HUD with light color + countdown.
    box_w, box_h = 0.24, 0.14
    box_x = 1.0 - box_w - 0.015
    box_y = 1.0 - box_h - 0.02
    rect = Rectangle(
        (box_x, box_y),
        box_w,
        box_h,
        transform=ax.transAxes,
        facecolor="white",
        edgecolor="#555555",
        linewidth=0.8,
        alpha=0.9,
        zorder=20,
    )
    ax.add_patch(rect)
    light = Circle(
        (box_x + 0.035, box_y + box_h - 0.04),
        0.015,
        transform=ax.transAxes,
        facecolor=color,
        edgecolor="#333333",
        linewidth=0.6,
        zorder=21,
    )
    ax.add_patch(light)
    ax.text(
        box_x + 0.06,
        box_y + box_h - 0.04,
        f"TL {state}",
        transform=ax.transAxes,
        fontsize=8,
        ha="left",
        va="center",
        color="#1A1A1A",
        zorder=21,
    )
    ax.text(
        box_x + 0.02,
        box_y + 0.05,
        f"Countdown: {countdown_text}",
        transform=ax.transAxes,
        fontsize=8,
        ha="left",
        va="center",
        color="#1A1A1A",
        zorder=21,
    )
    ax.text(
        box_x + 0.02,
        box_y + 0.02,
        f"R={red_count} Y={yellow_count} G={green_count}",
        transform=ax.transAxes,
        fontsize=7,
        ha="left",
        va="center",
        color="#555555",
        zorder=21,
    )


def apply_bev_limits(
    ax: plt.Axes,
    ego_points: List[Point2D],
    extra_points: Optional[List[Point2D]],
    map_layers: Optional[Dict[str, Any]],
    map_radius: float,
    use_global_frame: bool,
) -> None:
    if map_layers is not None:
        if use_global_frame:
            ox, oy = map_layers["origin_global"]
            ax.set_xlim(ox - map_radius, ox + map_radius)
            ax.set_ylim(oy - map_radius, oy + map_radius)
        else:
            ax.set_xlim(-map_radius, map_radius)
            ax.set_ylim(-map_radius, map_radius)
        return

    points = list(ego_points)
    if extra_points:
        points.extend(extra_points)
    xs = [p[0] for p in points]
    ys = [p[1] for p in points]
    if not xs or not ys:
        ax.set_xlim(-10, 10)
        ax.set_ylim(-10, 10)
        return
    margin = 6.0
    ax.set_xlim(min(xs) - margin, max(xs) + margin)
    ax.set_ylim(min(ys) - margin, max(ys) + margin)


