def render_animation_frames(
    trace: TraceDict,
    split_idx: int,
    use_global_frame: bool,
    map_radius: float,
    map_layers: Optional[Dict[str, Any]],
    map_style: str,
    show_route_nodes: bool,
    show_connector_nodes: bool,
    show_tl_hud: bool,
) -> List[Image.Image]:
    frames = trace["frames"]
    n = len(frames)
    split_idx = max(0, min(split_idx, n - 1))
    token = str(trace.get("token", "unknown"))

    ego_points, _, all_vehicles, vehicles_points = trace_to_series(trace, use_global_frame)
    origin_global = (float(frames[0]["ego"]["x"]), float(frames[0]["ego"]["y"]))
    origin_heading = float(frames[0]["ego"]["heading"])

    images: List[Image.Image] = []
    for t in range(n):
        fig, ax = plt.subplots(1, 1, figsize=(6.5, 6.5), dpi=120)
        draw_map_layers(
            ax,
            map_layers,
            map_style=map_style,
            show_route_nodes=show_route_nodes,
            show_connector_nodes=show_connector_nodes,
        )
        draw_traffic_lights(ax, trace, map_layers, t)
        if show_tl_hud:
            draw_traffic_light_hud(ax, trace, t, map_layers)

        path = ego_points[: t + 1]
        stage1 = path[: min(t, split_idx) + 1]
        stage2 = path[max(0, split_idx): t + 1] if t >= split_idx else []
        if stage1:
            ax.plot([p[0] for p in stage1], [p[1] for p in stage1], color="#E53935", lw=2.0, zorder=14)
        if stage2:
            ax.plot([p[0] for p in stage2], [p[1] for p in stage2], color="#00A86B", lw=2.0, zorder=14)

        draw_vehicle_boxes(
            ax=ax,
            vehicles=all_vehicles[t],
            use_global_frame=use_global_frame,
            origin_global=origin_global,
            origin_heading=origin_heading,
            color="#355C7D",
            fill_alpha=0.16,
            line_alpha=0.92,
            line_width=0.9,
        )
        draw_vehicle_boxes(
            ax=ax,
            vehicles=[ego_box_payload(frames[t])],
            use_global_frame=use_global_frame,
            origin_global=origin_global,
            origin_heading=origin_heading,
            color="#111111",
            fill_alpha=0.08,
            line_alpha=0.95,
            line_width=1.1,
        )

        curr_ego = ego_points[t]
        ax.scatter([curr_ego[0]], [curr_ego[1]], s=18, color="#111111", zorder=15)

        if split_idx <= t:
            split_pt = ego_points[split_idx]
            ax.scatter([split_pt[0]], [split_pt[1]], s=16, color="#F39C12", zorder=15)

        apply_bev_limits(ax, ego_points, vehicles_points[t], map_layers, map_radius, use_global_frame)
        ax.set_aspect("equal")
        ax.grid(True, alpha=0.2)
        ax.set_title(f"{token} | t={t}/{n - 1}", fontsize=10)
        ax.set_xlabel("x")
        ax.set_ylabel("y")

        buf = io.BytesIO()
        fig.tight_layout()
        fig.savefig(buf, format="png")
        plt.close(fig)
        buf.seek(0)
        with Image.open(buf) as frame:
            images.append(frame.convert("RGB"))
        buf.close()

    return images


def render_gif(
    trace: TraceDict,
    split_idx: int,
    use_global_frame: bool,
    map_radius: float,
    map_layers: Optional[Dict[str, Any]],
    map_style: str,
    show_route_nodes: bool,
    show_connector_nodes: bool,
    show_tl_hud: bool,
    out_gif: Path,
    fps: float,
) -> None:
    images = render_animation_frames(
        trace=trace,
        split_idx=split_idx,
        use_global_frame=use_global_frame,
        map_radius=map_radius,
        map_layers=map_layers,
        map_style=map_style,
        show_route_nodes=show_route_nodes,
        show_connector_nodes=show_connector_nodes,
        show_tl_hud=show_tl_hud,
    )

    out_gif.parent.mkdir(parents=True, exist_ok=True)
    duration_ms = int(round(1000.0 / max(1, fps)))
    images[0].save(out_gif, save_all=True, append_images=images[1:], duration=duration_ms, loop=0)
    for img in images:
        img.close()


def render_mp4(
    trace: TraceDict,
    split_idx: int,
    use_global_frame: bool,
    map_radius: float,
    map_layers: Optional[Dict[str, Any]],
    map_style: str,
    show_route_nodes: bool,
    show_connector_nodes: bool,
    show_tl_hud: bool,
    out_mp4: Path,
    fps: float,
    crf: int,
    ffmpeg_bin: str,
) -> None:
    images = render_animation_frames(
        trace=trace,
        split_idx=split_idx,
        use_global_frame=use_global_frame,
        map_radius=map_radius,
        map_layers=map_layers,
        map_style=map_style,
        show_route_nodes=show_route_nodes,
        show_connector_nodes=show_connector_nodes,
        show_tl_hud=show_tl_hud,
    )
    out_mp4.parent.mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory(prefix="vis_mp4_") as tmp_dir:
        tmp_path = Path(tmp_dir)
        for idx, image in enumerate(images):
            frame_path = tmp_path / f"frame_{idx:06d}.png"
            image.save(frame_path, format="PNG")

        ffmpeg_cmd = [
            ffmpeg_bin,
            "-y",
            "-framerate",
            str(max(1, fps)),
            "-i",
            str(tmp_path / "frame_%06d.png"),
            "-c:v",
            "libx264",
            "-pix_fmt",
            "yuv420p",
            "-crf",
            str(crf),
            "-movflags",
            "+faststart",
            str(out_mp4),
        ]
        result = subprocess.run(ffmpeg_cmd, capture_output=True, text=True)
        if result.returncode != 0:
            err_tail = "\n".join(result.stderr.splitlines()[-20:])
            raise RuntimeError(f"ffmpeg failed for {out_mp4}:\n{err_tail}")

    for img in images:
        img.close()


def output_path_for(input_file: Path, output_dir: Path, suffix: str) -> Path:
    stem = input_file.stem
    if stem.endswith("_vis"):
        stem = stem[:-4]
    return output_dir / f"{stem}{suffix}"


def output_path_for_stem(stem: str, output_dir: Path, suffix: str) -> Path:
    stem_clean = stem[:-4] if stem.endswith("_vis") else stem
    return output_dir / f"{stem_clean}{suffix}"


def _has_metric_cache_metadata(root: Path) -> bool:
    metadata_dir = root / "metadata"
    if not metadata_dir.exists() or not metadata_dir.is_dir():
        return False
    return any(p.suffix.lower() == ".csv" for p in metadata_dir.iterdir())


def resolve_metric_cache_root(input_path: Path) -> Path:
    p = input_path.expanduser().resolve()
    if _has_metric_cache_metadata(p):
        return p

    # Common case: user passes parent folder such as `metric_cache`, while actual root is `metric_cache/navmini`.
    if p.exists() and p.is_dir():
        children = [child for child in p.iterdir() if child.is_dir()]
        matched = [child for child in children if _has_metric_cache_metadata(child)]
        if len(matched) == 1:
            return matched[0]
        if len(matched) > 1:
            options = ", ".join(str(m) for m in matched)
            raise RuntimeError(
                f"Found multiple metric cache roots under {p}: {options}. "
                "Please pass one explicit path to --metric-cache-path."
            )

    # Also support passing deep token path; walk up to find first valid cache root.
    for parent in [p] + list(p.parents):
        if _has_metric_cache_metadata(parent):
            return parent

    raise RuntimeError(
        f"Invalid --metric-cache-path: {input_path}. "
        "Expected a directory containing 'metadata/*.csv' (e.g. metric_cache/navmini)."
    )


def _build_local_metric_cache_index(cache_root: Path) -> Dict[str, str]:
    index: Dict[str, str] = {}
    for metric_file in cache_root.rglob("metric_cache.pkl"):
        token = metric_file.parent.name
        index[token] = str(metric_file)
    return index


def build_metric_cache_loader(cache_root: Path) -> Any:
    loader = MetricCacheLoader(cache_root)
    missing_tokens = [token for token, file_path in loader.metric_cache_paths.items() if not Path(file_path).exists()]
    if not missing_tokens:
        return loader

    local_index = _build_local_metric_cache_index(cache_root)
    patched = 0
    for token in missing_tokens:
        local_path = local_index.get(token)
        if local_path is not None:
            loader.metric_cache_paths[token] = local_path
            patched += 1

    if patched > 0:
        print(
            f"[info] Metric cache metadata contained stale absolute paths; "
            f"patched {patched}/{len(missing_tokens)} token paths from local index."
        )

    return loader


def process_one_file(
    file_path: Path,
    output_dir: Path,
    split_idx_arg: Optional[int],
    box_frame: str,
    ego_box_frame: str,
    traffic_light_frame: str,
    use_global_frame: bool,
    dpi: int,
    fig_width: float,
    fig_height: float,
    save_svg: bool,
    map_radius: float,
    map_style: str,
    show_route_nodes: bool,
    show_connector_nodes: bool,
    show_tl_hud: bool,
    map_root_override: Optional[Path],
    metric_cache_loader: Optional[Any],
    map_api_cache: Dict[Tuple[str, str, str], Any],
    make_gif: bool,
    gif_fps: float,
    make_mp4: bool,
    mp4_fps: float,
    mp4_crf: int,
    ffmpeg_bin: str,
    sync_to_timestamps: bool,
    overwrite: bool,
    manifest_meta: Optional[Dict[str, Any]] = None,
    trace_override: Optional[TraceDict] = None,
    output_stem: Optional[str] = None,
) -> None:
    trace = trace_override if trace_override is not None else load_trace(file_path)
    validate_trace(trace, file_path)
    split_idx = split_idx_arg if split_idx_arg is not None else infer_split_index_from_trace(trace)
    box_frame_idx = parse_box_frame(box_frame, split_idx, int(trace["num_frames"]))
    ego_box_frame_idx = parse_box_frame(ego_box_frame, split_idx, int(trace["num_frames"]))
    traffic_light_frame_idx = parse_box_frame(traffic_light_frame, split_idx, int(trace["num_frames"]))

    map_layers = prepare_map_layers(
        metric_cache_loader=metric_cache_loader,
        map_api_cache=map_api_cache,
        trace=trace,
        use_global_frame=use_global_frame,
        map_radius=map_radius,
        map_root_override=map_root_override,
    )
    if metric_cache_loader is not None and map_layers is None:
        print(f"[warn] map not available for token={trace.get('token')} (metric cache lookup failed)")

    effective_gif_fps = float(gif_fps)
    effective_mp4_fps = float(mp4_fps)
    if sync_to_timestamps:
        realtime_fps = infer_realtime_fps_from_trace(trace)
        if realtime_fps is not None:
            effective_gif_fps = realtime_fps
            effective_mp4_fps = realtime_fps
            print(f"[info] token={trace.get('token')} realtime fps={realtime_fps:.3f}")
        else:
            print(f"[warn] token={trace.get('token')} has no valid timestamps; fallback to fixed fps.")

    stem = output_stem if output_stem is not None else file_path.stem
    out_png = output_path_for_stem(stem, output_dir, "_vis.png")
    out_svg = output_path_for_stem(stem, output_dir, "_vis.svg") if save_svg else None
    if overwrite or not out_png.exists():
        render_static_figure(
            trace=trace,
            split_idx=split_idx,
            box_frame_idx=box_frame_idx,
            ego_box_frame_idx=ego_box_frame_idx,
            traffic_light_frame_idx=traffic_light_frame_idx,
            use_global_frame=use_global_frame,
            dpi=dpi,
            map_radius=map_radius,
            map_layers=map_layers,
            map_style=map_style,
            show_route_nodes=show_route_nodes,
            show_connector_nodes=show_connector_nodes,
            show_tl_hud=show_tl_hud,
            fig_width=fig_width,
            fig_height=fig_height,
            out_png=out_png,
            out_svg=out_svg,
            manifest_meta=manifest_meta,
        )
        print(f"[saved] {out_png}")
        if out_svg is not None:
            print(f"[saved] {out_svg}")
    else:
        print(f"[skip]  exists: {out_png}")
        if out_svg is not None and (overwrite or not out_svg.exists()):
            render_static_figure(
                trace=trace,
                split_idx=split_idx,
                box_frame_idx=box_frame_idx,
                ego_box_frame_idx=ego_box_frame_idx,
                traffic_light_frame_idx=traffic_light_frame_idx,
                use_global_frame=use_global_frame,
                dpi=dpi,
                map_radius=map_radius,
                map_layers=map_layers,
                map_style=map_style,
                show_route_nodes=show_route_nodes,
                show_connector_nodes=show_connector_nodes,
                show_tl_hud=show_tl_hud,
                fig_width=fig_width,
                fig_height=fig_height,
                out_png=out_png,
                out_svg=out_svg,
                manifest_meta=manifest_meta,
            )
            print(f"[saved] {out_svg}")

    if make_gif:
        out_gif = output_path_for_stem(stem, output_dir, "_anim.gif")
        if overwrite or not out_gif.exists():
            render_gif(
                trace=trace,
                split_idx=split_idx,
                use_global_frame=use_global_frame,
                map_radius=map_radius,
                map_layers=map_layers,
                map_style=map_style,
                show_route_nodes=show_route_nodes,
                show_connector_nodes=show_connector_nodes,
                show_tl_hud=show_tl_hud,
                out_gif=out_gif,
                fps=effective_gif_fps,
            )
            print(f"[saved] {out_gif}")
        else:
            print(f"[skip]  exists: {out_gif}")

    if make_mp4:
        out_mp4 = output_path_for_stem(stem, output_dir, "_anim.mp4")
        if overwrite or not out_mp4.exists():
            render_mp4(
                trace=trace,
                split_idx=split_idx,
                use_global_frame=use_global_frame,
                map_radius=map_radius,
                map_layers=map_layers,
                map_style=map_style,
                show_route_nodes=show_route_nodes,
                show_connector_nodes=show_connector_nodes,
                show_tl_hud=show_tl_hud,
                out_mp4=out_mp4,
                fps=effective_mp4_fps,
                crf=mp4_crf,
                ffmpeg_bin=ffmpeg_bin,
            )
            print(f"[saved] {out_mp4}")
        else:
            print(f"[skip]  exists: {out_mp4}")


def main() -> None:
    args = parse_args()
    effective_history_frames = -1 if args.use_full_log else args.history_frames
    effective_future_frames = -1 if args.use_full_log else args.future_frames

    scene_pairs = collect_scene_pairs(args.scene_list_file, args.scene_list)
    manifest_meta_by_file: Dict[str, Dict[str, Any]] = {}
    input_files: List[Path] = []
    if not scene_pairs:
        if args.manifest is not None:
            input_files, manifest_meta_by_file = list_files_from_manifest(
                manifest_path=args.manifest,
                status_filter=args.status_filter,
                reason_filter=args.reason_filter,
                max_files=args.max_files,
            )
        else:
            input_files = list_input_files(args.input, args.glob, args.max_files)
        if not input_files:
            if args.manifest is not None:
                raise RuntimeError(
                    f"No files found from manifest={args.manifest} with status={args.status_filter}, "
                    f"reason={args.reason_filter}"
                )
            raise RuntimeError(f"No files found under {args.input} with pattern {args.glob}")

    if args.output_dir is not None:
        output_dir = args.output_dir
    elif scene_pairs:
        output_dir = Path("output/scene_token_visuals")
    elif args.manifest is not None:
        output_dir = args.manifest.parent
    elif args.input.is_file():
        output_dir = args.input.parent
    else:
        output_dir = args.input

    metric_cache_loader: Optional[Any] = None
    map_api_cache: Dict[Tuple[str, str, str], Any] = {}
    if args.metric_cache_path is not None:
        if not HAS_MAP_SUPPORT:
            raise RuntimeError(f"Map support imports failed: {MAP_IMPORT_ERROR}")
        if args.map_root_override is not None and not args.map_root_override.exists():
            raise RuntimeError(f"--map-root-override does not exist: {args.map_root_override}")
        cache_root = resolve_metric_cache_root(args.metric_cache_path)
        metric_cache_loader = build_metric_cache_loader(cache_root)
        print(f"Map overlay enabled from metric cache: {cache_root}")
        if args.map_root_override is not None:
            print(f"Using map root override: {args.map_root_override.resolve()}")

    if scene_pairs:
        mini_log_root = args.mini_log_root.expanduser().resolve()
        if not mini_log_root.exists():
            raise FileNotFoundError(f"--mini-log-root does not exist: {mini_log_root}")
        print(f"Found {len(scene_pairs)} scene pair(s). Writing to: {output_dir.resolve()}")

        log_cache: Dict[str, List[Dict[str, Any]]] = {}
        num_ok = 0
        for log_name, token in scene_pairs:
            if log_name not in log_cache:
                log_file = mini_log_root / f"{log_name}.pkl"
                if not log_file.exists():
                    print(f"[warn] missing log file: {log_file}")
                    log_cache[log_name] = []
                else:
                    with log_file.open("rb") as f:
                        log_cache[log_name] = pickle.load(f)
            trace = build_trace_from_scene_pair(
                log_frames=log_cache[log_name],
                log_name=log_name,
                token=token,
                history_frames=effective_history_frames,
                future_frames=effective_future_frames,
            )
            if trace is None:
                print(f"[warn] token not found in log: {log_name} / {token}")
                continue

            stem = f"{log_name}__{token}"
            process_one_file(
                file_path=Path(f"{stem}.json"),
                output_dir=output_dir,
                split_idx_arg=args.split_index,
                box_frame=args.box_frame,
                ego_box_frame=args.ego_box_frame,
                traffic_light_frame=args.traffic_light_frame,
                use_global_frame=args.global_frame,
                dpi=args.dpi,
                fig_width=args.fig_width,
                fig_height=args.fig_height,
                save_svg=args.save_svg,
                map_radius=args.map_radius,
                map_style=args.map_style,
                show_route_nodes=(not args.hide_route_nodes),
                show_connector_nodes=(not args.hide_connector_nodes),
                show_tl_hud=args.show_tl_hud,
                map_root_override=args.map_root_override,
                metric_cache_loader=metric_cache_loader,
                map_api_cache=map_api_cache,
                make_gif=args.make_gif,
                gif_fps=args.gif_fps,
                make_mp4=args.make_mp4,
                mp4_fps=args.mp4_fps,
                mp4_crf=args.mp4_crf,
                ffmpeg_bin=args.ffmpeg_bin,
                sync_to_timestamps=args.sync_to_timestamps,
                overwrite=args.overwrite,
                manifest_meta={"result_status": "scene_pair", "log_name": log_name},
                trace_override=trace,
                output_stem=stem,
            )
            num_ok += 1
        print(f"[done] rendered {num_ok}/{len(scene_pairs)} scene pair(s).")
        return

    print(f"Found {len(input_files)} file(s). Writing to: {output_dir.resolve()}")
    for file_path in input_files:
        process_one_file(
            file_path=file_path,
            output_dir=output_dir,
            split_idx_arg=args.split_index,
            box_frame=args.box_frame,
            ego_box_frame=args.ego_box_frame,
            traffic_light_frame=args.traffic_light_frame,
            use_global_frame=args.global_frame,
            dpi=args.dpi,
            fig_width=args.fig_width,
            fig_height=args.fig_height,
            save_svg=args.save_svg,
            map_radius=args.map_radius,
            map_style=args.map_style,
            show_route_nodes=(not args.hide_route_nodes),
            show_connector_nodes=(not args.hide_connector_nodes),
            show_tl_hud=args.show_tl_hud,
            map_root_override=args.map_root_override,
            metric_cache_loader=metric_cache_loader,
            map_api_cache=map_api_cache,
            make_gif=args.make_gif,
            gif_fps=args.gif_fps,
            make_mp4=args.make_mp4,
            mp4_fps=args.mp4_fps,
            mp4_crf=args.mp4_crf,
            ffmpeg_bin=args.ffmpeg_bin,
            sync_to_timestamps=args.sync_to_timestamps,
            overwrite=args.overwrite,
            manifest_meta=manifest_meta_by_file.get(str(file_path.resolve())),
        )


if __name__ == "__main__":
    main()
