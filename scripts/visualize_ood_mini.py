def list_input_files(input_path: Path, pattern: str, max_files: Optional[int]) -> List[Path]:
    if input_path.is_file():
        return [input_path]
    if not input_path.exists():
        raise FileNotFoundError(f"Input does not exist: {input_path}")
    files = sorted(input_path.glob(pattern))
    if not files and pattern.endswith(".json"):
        files = sorted(input_path.glob(pattern.replace(".json", ".pkl")))
    if max_files is not None:
        files = files[:max_files]
    return files


def list_files_from_manifest(
    manifest_path: Path,
    status_filter: str,
    reason_filter: Optional[str],
    max_files: Optional[int],
) -> Tuple[List[Path], Dict[str, Dict[str, Any]]]:
    if not manifest_path.exists():
        raise FileNotFoundError(f"Manifest does not exist: {manifest_path}")
    files: List[Path] = []
    meta_by_file: Dict[str, Dict[str, Any]] = {}
    seen: set[str] = set()
    with manifest_path.open("r", encoding="utf-8") as f:
        for raw in f:
            line = raw.strip()
            if not line:
                continue
            entry = json.loads(line)
            status = str(entry.get("result_status", "success"))
            if status_filter != "all" and status != status_filter:
                continue
            if reason_filter is not None and str(entry.get("reject_reason")) != reason_filter:
                continue
            file_candidate = entry.get("json_path") or entry.get("pkl_path")
            if not file_candidate:
                continue
            p = Path(str(file_candidate)).expanduser()
            if not p.exists():
                continue
            key = str(p.resolve())
            if key in seen:
                continue
            seen.add(key)
            files.append(p)
            meta_by_file[key] = entry
            if max_files is not None and len(files) >= max_files:
                break
    return files, meta_by_file


SCENE_PAIR_PATTERN = re.compile(r"([^\s/]+)\s*/\s*([0-9a-fA-F]{16})")


def parse_scene_pairs_text(text: str) -> List[Tuple[str, str]]:
    pairs: List[Tuple[str, str]] = []
    seen: set[Tuple[str, str]] = set()
    for match in SCENE_PAIR_PATTERN.finditer(text):
        log_name = str(match.group(1)).strip()
        token = str(match.group(2)).strip().lower()
        pair = (log_name, token)
        if pair in seen:
            continue
        seen.add(pair)
        pairs.append(pair)
    return pairs


def collect_scene_pairs(scene_list_file: Optional[Path], inline_scene_list: Optional[str]) -> List[Tuple[str, str]]:
    chunks: List[str] = []
    if scene_list_file is not None:
        if not scene_list_file.exists():
            raise FileNotFoundError(f"scene list file does not exist: {scene_list_file}")
        chunks.append(scene_list_file.read_text(encoding="utf-8"))
    if inline_scene_list:
        chunks.append(inline_scene_list)
    if not chunks:
        return []
    return parse_scene_pairs_text("\n".join(chunks))


def load_trace(path: Path) -> TraceDict:
    suffix = path.suffix.lower()
    if suffix == ".json":
        return json.loads(path.read_text(encoding="utf-8"))
    if suffix == ".pkl":
        with path.open("rb") as f:
            return pickle.load(f)
    raise ValueError(f"Unsupported file format: {path}")


def validate_trace(trace: TraceDict, path: Path) -> None:
    required_keys = {"token", "num_frames", "frames", "stage1_score"}
    missing = required_keys - set(trace.keys())
    if missing:
        raise ValueError(f"{path}: missing keys {sorted(missing)}")
    if not isinstance(trace["frames"], list) or len(trace["frames"]) == 0:
        raise ValueError(f"{path}: frames must be a non-empty list")


def infer_split_index(num_frames: int) -> int:
    if num_frames <= 1:
        return 0
    if num_frames % 2 == 1:
        return (num_frames - 1) // 2
    return num_frames // 2


def infer_split_index_from_trace(trace: TraceDict) -> int:
    n = int(trace.get("num_frames", 0))
    if n <= 1:
        return 0
    strong = trace.get("strong_longtail", {})
    longtail = trace.get("longtail", {})
    for bucket in (strong, longtail):
        if isinstance(bucket, dict) and "split_idx" in bucket:
            try:
                return max(0, min(int(round(float(bucket["split_idx"]))), n - 1))
            except Exception:
                pass
    stage2 = trace.get("stage2_score")
    if not isinstance(stage2, dict) or not stage2:
        return n - 1
    return infer_split_index(n)


def parse_box_frame(value: str, split_idx: int, num_frames: int) -> int:
    if value == "start":
        return 0
    if value == "split":
        return split_idx
    if value == "end":
        return num_frames - 1
    idx = int(value)
    return max(0, min(idx, num_frames - 1))


def yaw_from_transform_matrix(ego2global: np.ndarray) -> float:
    return float(math.atan2(float(ego2global[1, 0]), float(ego2global[0, 0])))


def transform_local_xy_to_global(ego2global: np.ndarray, x_local: float, y_local: float) -> Tuple[float, float]:
    point_local = np.array([x_local, y_local, 0.0, 1.0], dtype=np.float64)
    point_global = ego2global @ point_local
    return float(point_global[0]), float(point_global[1])


def build_trace_from_scene_pair(
    log_frames: List[Dict[str, Any]],
    log_name: str,
    token: str,
    history_frames: int,
    future_frames: int,
) -> Optional[TraceDict]:
    token_to_index = {str(frame.get("token")): idx for idx, frame in enumerate(log_frames)}
    if token not in token_to_index:
        return None

    center_idx = token_to_index[token]
    start_idx = 0 if history_frames < 0 else max(0, center_idx - max(0, history_frames))
    end_idx = (len(log_frames) - 1) if future_frames < 0 else min(len(log_frames) - 1, center_idx + max(0, future_frames))
    scene_frames = log_frames[start_idx : end_idx + 1]
    split_idx = center_idx - start_idx

    trace_frames: List[Dict[str, Any]] = []
    for frame in scene_frames:
        ego2global = np.asarray(frame["ego2global"], dtype=np.float64)
        ego_x = float(frame["ego2global_translation"][0])
        ego_y = float(frame["ego2global_translation"][1])
        ego_heading = yaw_from_transform_matrix(ego2global)
        ego_vx, ego_vy = float(frame["ego_dynamic_state"][0]), float(frame["ego_dynamic_state"][1])
        ego_speed = float(math.hypot(ego_vx, ego_vy))

        boxes = frame["anns"]["gt_boxes"]
        names = frame["anns"]["gt_names"]
        vehicles: List[Dict[str, Any]] = []
        for box, name in zip(boxes, names):
            # Keep vehicle-class boxes only for readability.
            if str(name) != "vehicle":
                continue
            x_local, y_local = float(box[0]), float(box[1])
            length, width = float(box[3]), float(box[4])
            heading_local = float(box[6])
            vx_global, vy_global = transform_local_xy_to_global(ego2global, x_local, y_local)
            vehicles.append(
                {
                    "x": vx_global,
                    "y": vy_global,
                    "heading": normalize_angle(ego_heading + heading_local),
                    "width": width,
                    "length": length,
                }
            )

        traffic_lights = [[str(lane_connector_id), bool(is_red)] for lane_connector_id, is_red in frame["traffic_lights"]]
        trace_frames.append(
            {
                "token": str(frame["token"]),
                "timestamp": int(frame.get("timestamp", 0)),
                "ego": {
                    "x": ego_x,
                    "y": ego_y,
                    "heading": ego_heading,
                    "velocity": ego_speed,
                },
                "vehicles": vehicles,
                "traffic_lights": traffic_lights,
            }
        )

    return {
        "token": token,
        "log_name": log_name,
        "num_frames": len(trace_frames),
        "frames": trace_frames,
        "stage1_score": {},
        "stage2_score": {},
        "strong_longtail": {"split_idx": split_idx},
    }


def build_diagnostic_lines(trace: TraceDict, manifest_meta: Optional[Dict[str, Any]]) -> List[str]:
    def _sf(v: Any) -> float:
        try:
            return float(v)
        except Exception:
            return float("nan")

    lines: List[str] = []
    merged: Dict[str, Any] = {}
    if isinstance(manifest_meta, dict):
        merged.update(manifest_meta)
    merged.update(trace)

    status = merged.get("result_status")
    reason = merged.get("reject_reason")
    stage = merged.get("search_stage")
    if status is not None or reason is not None or stage is not None:
        lines.append(f"status={status}, reason={reason}, stage={stage}")

    strong = merged.get("strong_longtail")
    if isinstance(strong, dict):
        lines.append(
            "strong: "
            f"score={_sf(strong.get('strong_longtail_score')):.3f}, "
            f"d1={_sf(strong.get('stage1_min_dist_m')):.2f}m, "
            f"d2={_sf(strong.get('stage2_min_dist_m')):.2f}m, "
            f"disp2={_sf(strong.get('stage2_displacement_m')):.2f}m"
        )

    lt = merged.get("longtail")
    if isinstance(lt, dict):
        lines.append(
            "ranked: "
            f"score={_sf(lt.get('longtail_score')):.3f}, "
            f"risk={_sf(lt.get('risk_score')):.3f}, "
            f"recovery={_sf(lt.get('recovery_score')):.3f}, "
            f"cont={_sf(lt.get('continuity_score')):.3f}"
        )
    return lines


def normalize_angle(angle: float) -> float:
    return (angle + math.pi) % (2 * math.pi) - math.pi


def to_local(points: Sequence[Point2D], origin: Point2D, heading: float) -> List[Point2D]:
    ox, oy = origin
    c = math.cos(heading)
    s = math.sin(heading)
    out: List[Point2D] = []
    for x, y in points:
        dx, dy = x - ox, y - oy
        lx = c * dx + s * dy
        ly = -s * dx + c * dy
        out.append((lx, ly))
    return out


def trace_to_series(
    trace: TraceDict,
    use_global_frame: bool,
) -> Tuple[List[Point2D], List[float], List[List[Dict[str, Any]]], List[List[Point2D]]]:
    frames = trace["frames"]
    ego_points_global = [(float(f["ego"]["x"]), float(f["ego"]["y"])) for f in frames]
    ego_speed = [float(f["ego"]["velocity"]) for f in frames]
    all_vehicles = [f.get("vehicles", []) for f in frames]

    if use_global_frame:
        ego_points = ego_points_global
        vehicles_points = [[(float(v["x"]), float(v["y"])) for v in vehicles] for vehicles in all_vehicles]
        return ego_points, ego_speed, all_vehicles, vehicles_points

    init_heading = float(frames[0]["ego"]["heading"])
    origin = ego_points_global[0]
    ego_points = to_local(ego_points_global, origin, init_heading)
    vehicles_points = []
    for vehicles in all_vehicles:
        pts = [(float(v["x"]), float(v["y"])) for v in vehicles]
        vehicles_points.append(to_local(pts, origin, init_heading))
    return ego_points, ego_speed, all_vehicles, vehicles_points


def nearest_vehicle_distance(ego_points: Sequence[Point2D], vehicles_points: Sequence[Sequence[Point2D]]) -> List[float]:
    dist_list: List[float] = []
    for ego, vehicles in zip(ego_points, vehicles_points):
        ex, ey = ego
        if not vehicles:
            dist_list.append(float("nan"))
            continue
        dmin = min(math.hypot(vx - ex, vy - ey) for vx, vy in vehicles)
        dist_list.append(dmin)
    return dist_list


