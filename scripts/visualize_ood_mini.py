def oriented_box_corners(center_x: float, center_y: float, heading: float, length: float, width: float) -> List[Point2D]:
    half_l = 0.5 * length
    half_w = 0.5 * width
    local = [(half_l, half_w), (half_l, -half_w), (-half_l, -half_w), (-half_l, half_w)]
    c = math.cos(heading)
    s = math.sin(heading)
    return [
        (center_x + c * dx - s * dy, center_y + s * dx + c * dy)
        for dx, dy in local
    ]


def ego_box_payload(frame: Dict[str, Any]) -> Dict[str, float]:
    ego = frame["ego"]
    return {
        "x": float(ego["x"]),
        "y": float(ego["y"]),
        "heading": float(ego.get("heading", 0.0)),
        # Fallback dimensions if ego size is not serialized in trace.
        "width": float(ego.get("width", 2.0)),
        "length": float(ego.get("length", 4.8)),
    }


def draw_vehicle_boxes(
    ax: plt.Axes,
    vehicles: Sequence[Dict[str, Any]],
    use_global_frame: bool,
    origin_global: Point2D,
    origin_heading: float,
    color: str = "#355C7D",
    fill_alpha: float = 0.12,
    line_alpha: float = 0.9,
    line_width: float = 1.0,
    label: Optional[str] = None,
    zorder_base: float = 12.0,
) -> None:
    label_used = False
    for v in vehicles:
        cx = float(v["x"])
        cy = float(v["y"])
        heading = float(v.get("heading", 0.0))
        width = float(v.get("width", 1.8))
        length = float(v.get("length", 4.5))
        if not use_global_frame:
            cx, cy = to_local([(cx, cy)], origin_global, origin_heading)[0]
            heading = normalize_angle(heading - origin_heading)
        corners = oriented_box_corners(cx, cy, heading, length, width)
        patch = MplPolygon(
            corners,
            closed=True,
            facecolor=color,
            edgecolor=color,
            linewidth=line_width,
            alpha=fill_alpha,
            zorder=zorder_base,
            label=(label if (label and not label_used) else None),
        )
        ax.add_patch(patch)
        ax.plot(
            [p[0] for p in corners] + [corners[0][0]],
            [p[1] for p in corners] + [corners[0][1]],
            color=color,
            lw=line_width,
            alpha=line_alpha,
            zorder=zorder_base + 0.1,
        )
        label_used = True


def _iter_polygon_exteriors(geometry: Any) -> List[List[Point2D]]:
    if geometry is None:
        return []
    if hasattr(geometry, "geoms"):
        out: List[List[Point2D]] = []
        for g in geometry.geoms:
            out.extend(_iter_polygon_exteriors(g))
        return out
    if not hasattr(geometry, "exterior"):
        return []
    coords = [(float(x), float(y)) for x, y, *_ in geometry.exterior.coords]
    return [coords]


def _iter_lines(geometry: Any) -> List[List[Point2D]]:
    if geometry is None:
        return []
    if hasattr(geometry, "geoms"):
        out: List[List[Point2D]] = []
        for g in geometry.geoms:
            out.extend(_iter_lines(g))
        return out
    if not hasattr(geometry, "coords"):
        return []
    coords = [(float(x), float(y)) for x, y, *_ in geometry.coords]
    return [coords]


def _to_plot_coords(points: List[Point2D], use_global_frame: bool, origin: Point2D, heading: float) -> List[Point2D]:
    if use_global_frame:
        return points
    return to_local(points, origin, heading)


def prepare_map_layers(
    metric_cache_loader: Optional[Any],
    map_api_cache: Dict[Tuple[str, str, str], Any],
    trace: TraceDict,
    use_global_frame: bool,
    map_radius: float,
    map_root_override: Optional[Path],
) -> Optional[Dict[str, Any]]:
    if metric_cache_loader is None:
        return None

    token = str(trace["token"])
    try:
        metric_cache = metric_cache_loader.get_from_token(token)
    except Exception:
        return None

    params = metric_cache.map_parameters
    map_root = str(map_root_override.resolve()) if map_root_override is not None else str(params.map_root)
    key = (map_root, str(params.map_version), str(params.map_name))
    try:
        if key not in map_api_cache:
            map_api_cache[key] = get_maps_api(*key)
        map_api = map_api_cache[key]
    except Exception:
        return None

    first = trace["frames"][0]["ego"]
    origin_global = (float(first["x"]), float(first["y"]))
    origin_heading = float(first["heading"])
    origin_state = StateSE2(origin_global[0], origin_global[1], origin_heading)

    polygon_layer_specs: List[Tuple[str, Any]] = [
        ("lane", SemanticMapLayer.LANE),
        ("lane_connector", SemanticMapLayer.LANE_CONNECTOR),
        ("intersection", SemanticMapLayer.INTERSECTION),
        ("crosswalk", SemanticMapLayer.CROSSWALK),
        ("stop_line", SemanticMapLayer.STOP_LINE),
        ("walkway", SemanticMapLayer.WALKWAYS),
        ("carpark", SemanticMapLayer.CARPARK_AREA),
    ]
    polyline_layer_specs: List[Tuple[str, Any]] = [
        ("lane_baseline", SemanticMapLayer.LANE),
        ("lane_connector_baseline", SemanticMapLayer.LANE_CONNECTOR),
    ]
    requested_layers = list({layer for _, layer in polygon_layer_specs + polyline_layer_specs})
    map_object_dict = map_api.get_proximal_map_objects(
        point=origin_state.point,
        radius=map_radius,
        layers=requested_layers,
    )

    polygons_by_layer: Dict[str, List[List[Point2D]]] = {name: [] for name, _ in polygon_layer_specs}
    lines_by_layer: Dict[str, List[List[Point2D]]] = {name: [] for name, _ in polyline_layer_specs}
    route_lines: List[List[Point2D]] = []

    for layer_name, layer in polygon_layer_specs:
        for map_object in map_object_dict.get(layer, []):
            for poly in _iter_polygon_exteriors(getattr(map_object, "polygon", None)):
                polygons_by_layer[layer_name].append(_to_plot_coords(poly, use_global_frame, origin_global, origin_heading))

    for layer_name, layer in polyline_layer_specs:
        for map_object in map_object_dict.get(layer, []):
            base = getattr(getattr(map_object, "baseline_path", None), "linestring", None)
            for line in _iter_lines(base):
                lines_by_layer[layer_name].append(_to_plot_coords(line, use_global_frame, origin_global, origin_heading))

    for lane_id in metric_cache.route_lane_ids:
        lane = map_api.get_map_object(lane_id, SemanticMapLayer.LANE)
        if lane is None:
            lane = map_api.get_map_object(lane_id, SemanticMapLayer.LANE_CONNECTOR)
        if lane is None:
            continue
        base = getattr(getattr(lane, "baseline_path", None), "linestring", None)
        for line in _iter_lines(base):
            route_lines.append(_to_plot_coords(line, use_global_frame, origin_global, origin_heading))

    def _dedup_nodes(nodes: List[Point2D], precision: int = 2) -> List[Point2D]:
        seen: set[Tuple[float, float]] = set()
        out: List[Point2D] = []
        for x, y in nodes:
            key = (round(float(x), precision), round(float(y), precision))
            if key in seen:
                continue
            seen.add(key)
            out.append((float(x), float(y)))
        return out

    route_nodes_raw: List[Point2D] = []
    for line in route_lines:
        if len(line) >= 2:
            route_nodes_raw.append(line[0])
            route_nodes_raw.append(line[-1])
    route_nodes = _dedup_nodes(route_nodes_raw, precision=2)

    connector_nodes_raw: List[Point2D] = []
    for key in ("lane_baseline", "lane_connector_baseline"):
        for line in lines_by_layer.get(key, []):
            if len(line) >= 2:
                connector_nodes_raw.append(line[0])
                connector_nodes_raw.append(line[-1])
    connector_nodes = _dedup_nodes(connector_nodes_raw, precision=2)

    traffic_lights_by_frame: List[Dict[str, List[List[Point2D]]]] = []
    for frame in trace.get("frames", []):
        traffic_light_entries = frame.get("traffic_lights", [])
        red_polygons: List[List[Point2D]] = []
        green_polygons: List[List[Point2D]] = []
        if isinstance(traffic_light_entries, list):
            for entry in traffic_light_entries:
                if not isinstance(entry, (list, tuple)) or len(entry) != 2:
                    continue
                lane_connector_id = str(entry[0])
                is_red = bool(entry[1])
                lane_connector = map_api.get_map_object(lane_connector_id, SemanticMapLayer.LANE_CONNECTOR)
                if lane_connector is None:
                    continue
                for poly in _iter_polygon_exteriors(getattr(lane_connector, "polygon", None)):
                    poly_plot = _to_plot_coords(poly, use_global_frame, origin_global, origin_heading)
                    if is_red:
                        red_polygons.append(poly_plot)
                    else:
                        green_polygons.append(poly_plot)
        traffic_lights_by_frame.append({"red": red_polygons, "green": green_polygons})

    # Build TL anchor points on stop lines per controlled lane-connector:
    # traffic_light -> lane_connector -> stop_line center(s)
    tl_lane_ids: set[str] = set()
    for frame in trace.get("frames", []):
        entries = frame.get("traffic_lights", [])
        if not isinstance(entries, list):
            continue
        for entry in entries:
            if isinstance(entry, (list, tuple)) and len(entry) >= 1:
                tl_lane_ids.add(str(entry[0]))

    tl_anchors_by_lane_connector: Dict[str, List[Point2D]] = {}
    for lane_connector_id in sorted(tl_lane_ids):
        lane_connector = map_api.get_map_object(lane_connector_id, SemanticMapLayer.LANE_CONNECTOR)
        if lane_connector is None:
            continue

        anchors: List[Point2D] = []
        stop_lines = getattr(lane_connector, "stop_lines", None) or []
        for stop_line in stop_lines:
            poly = getattr(stop_line, "polygon", None)
            if poly is None:
                continue
            centroid = poly.centroid
            anchors.append(
                _to_plot_coords(
                    [(float(centroid.x), float(centroid.y))],
                    use_global_frame,
                    origin_global,
                    origin_heading,
                )[0]
            )
        if not anchors:
            # Fallback: use lane-connector polygon centroid if stop line unavailable.
            lc_poly = getattr(lane_connector, "polygon", None)
            if lc_poly is not None:
                c = lc_poly.centroid
                anchors.append(
                    _to_plot_coords(
                        [(float(c.x), float(c.y))],
                        use_global_frame,
                        origin_global,
                        origin_heading,
                    )[0]
                )
        if anchors:
            tl_anchors_by_lane_connector[lane_connector_id] = anchors

    return {
        "polygons_by_layer": polygons_by_layer,
        "lines_by_layer": lines_by_layer,
        "route_lines": route_lines,
        "route_nodes": route_nodes,
        "connector_nodes": connector_nodes,
        "traffic_lights_by_frame": traffic_lights_by_frame,
        "tl_anchors_by_lane_connector": tl_anchors_by_lane_connector,
        "route_lane_ids_set": {str(lane_id) for lane_id in metric_cache.route_lane_ids},
        "origin_global": [origin_global[0], origin_global[1]],
    }


